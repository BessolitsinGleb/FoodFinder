#!/bin/sh
# Старт контейнера: миграции, затем API.
set -e

alembic upgrade head

# Один воркер: поиск поставщиков идёт фоновой задачей внутри процесса, а при старте
# "зависшие" поиски помечаются упавшими — второй воркер оборвал бы чужой поиск.
# --proxy-headers: за прокси Railway реальный IP клиента берётся из X-Forwarded-For
# (нужно ограничителю запросов для незалогиненных).
exec uvicorn main:app \
  --host 0.0.0.0 \
  --port "${PORT:-8000}" \
  --proxy-headers \
  --forwarded-allow-ips="*"
